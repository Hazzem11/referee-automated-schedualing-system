CREATE TABLE referees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    email VARCHAR(255),
    experience_level INTEGER NOT NULL DEFAULT 1,
    home_location VARCHAR(255),
    home_place_id VARCHAR(255),
    home_lat DOUBLE PRECISION,
    home_lng DOUBLE PRECISION,
    max_travel_distance INTEGER NOT NULL DEFAULT 50,
    preferred_locations VARCHAR(2000),
    max_games_per_week INTEGER NOT NULL DEFAULT 3,
    current_games_this_week INTEGER NOT NULL DEFAULT 0,
    availability_json TEXT,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP
);

CREATE TABLE games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    location VARCHAR(255),
    location_place_id VARCHAR(255),
    location_lat DOUBLE PRECISION,
    location_lng DOUBLE PRECISION,
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    level VARCHAR(255),
    game_level INTEGER NOT NULL DEFAULT 1,
    required_experience_level INTEGER NOT NULL DEFAULT 1,
    required_referees INTEGER NOT NULL DEFAULT 1,
    number_of_games INTEGER,
    type VARCHAR(255),
    assigned BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT,
    referee_id BIGINT,
    slot_index INTEGER NOT NULL,
    published_at TIMESTAMP
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255),
    role VARCHAR(20) NOT NULL,
    referee_id BIGINT,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP
);

CREATE TABLE invite_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(64) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    referee_id BIGINT,
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    created_at TIMESTAMP
);
